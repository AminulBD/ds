def log(msg: str) -> None:
    print(msg, file=sys.stderr, flush=True)


def read_json(path: Path, default=None):
    if not path.exists():
        return default
    with path.open() as fh:
        return json.load(fh)


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w") as fh:
        json.dump(data, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    tmp.replace(path)


def random_label(n: int = 16) -> str:
    alphabet = string.ascii_lowercase + string.digits
    # Never start with a digit or end with a hyphen; some registries reject
    # such queries outright and the refusal would be read as a dead server.
    return random.choice(string.ascii_lowercase) + "".join(
        random.choice(alphabet) for _ in range(n - 1)
    )


# --------------------------------------------------------------------------
# per-host pacing
# --------------------------------------------------------------------------


class HostPacer:
    """One in-flight query per *backend*, with a minimum gap between them.

    Pacing by hostname is not enough to be polite. Nearly every gTLD publishes
    its own `whois.nic.<tld>`, but hundreds of those are CNAMEs onto a handful
    of shared registry back ends — Identity Digital, CentralNic, GoDaddy
    Registry. Treating them as separate hosts would let this script hammer one
    machine from twenty directions at once. So the pacing key is the address
    the name resolves to, and every TLD sharing a back end queues behind the
    same gap.
    """

    # Consecutive failures before a back end is rested, and for how long.
    # Resting rather than dropping matters: hundreds of TLDs can sit behind one
    # address, and a minute of rate limiting must not disqualify all of them
    # for the rest of the run.
    GIVE_UP_AFTER = 4
    COOLDOWN = 120.0

    def __init__(self, gap: float):
        self.gap = gap
        self._lock = threading.Lock()
        self._locks: dict[str, threading.Lock] = {}
        self._last: dict[str, float] = {}
        self._fails: dict[str, int] = {}
        self._rested_until: dict[str, float] = {}
        self._keys: dict[str, str] = {}

    def key(self, host: str) -> str:
        """The back end `host` sits on, falling back to the name itself."""
        with self._lock:
            cached = self._keys.get(host)
        if cached is not None:
            return cached
        try:
            key = socket.gethostbyname(host)
        except OSError:
            key = host
        with self._lock:
            self._keys[host] = key
        return key

    def _lock_for(self, host: str) -> threading.Lock:
        with self._lock:
            return self._locks.setdefault(host, threading.Lock())

    def dead(self, host: str) -> bool:
        """Is this back end resting after a run of failures?"""
        key = self.key(host)
        with self._lock:
            return time.monotonic() < self._rested_until.get(key, 0.0)

    def note(self, host: str, ok: bool) -> None:
        key = self.key(host)
        with self._lock:
            if ok:
                self._fails[key] = 0
                return
            fails = self._fails.get(key, 0) + 1
            self._fails[key] = fails
            if fails >= self.GIVE_UP_AFTER:
                # Rest it, and come back with the counter one short of the
                # threshold so a single further failure rests it again.
                self._rested_until[key] = time.monotonic() + self.COOLDOWN
                self._fails[key] = self.GIVE_UP_AFTER - 1

    def __call__(self, host: str):
        return _Paced(self, host)


class _Paced:
    def __init__(self, pacer: HostPacer, host: str):
        self.pacer, self.host = pacer, pacer.key(host)

    def __enter__(self):
        self.lock = self.pacer._lock_for(self.host)
        self.lock.acquire()
        last = self.pacer._last.get(self.host)
        if last is not None:
            wait = self.pacer.gap - (time.monotonic() - last)
            if wait > 0:
                time.sleep(wait)
        return self

    def __exit__(self, *exc):
        self.pacer._last[self.host] = time.monotonic()
        self.lock.release()
        return False


# --------------------------------------------------------------------------
# WHOIS over port 43
# --------------------------------------------------------------------------


def whois_query(host: str, query: str, timeout: float = 15.0) -> str:
    sock = socket.create_connection((host, 43), timeout)
    try:
        sock.settimeout(timeout)
        sock.sendall(query.encode("utf-8", "replace"))
        chunks, total = [], 0
        deadline = time.monotonic() + timeout
        while total < 256 * 1024:
            if time.monotonic() > deadline:
                break
            data = sock.recv(8192)
            if not data:
                break
            chunks.append(data)
            total += len(data)
    finally:
        sock.close()
    return b"".join(chunks).decode("utf-8", "replace").replace("\r\n", "\n")


def whois_ask(pacer: HostPacer, host: str, domain: str, retries: int = 2) -> tuple[str | None, str | None]:
    """-> (response, error). Retries only what is worth retrying."""
    if pacer.dead(host):
        return None, "back end resting after repeated failures"
    last_err = None
    for attempt in range(retries + 1):
        if STOP.is_set():
            return None, "interrupted"
        try:
            with pacer(host):
                raw = whois_query(host, format_query(host, domain))
            pacer.note(host, True)
            return raw, None
        except (socket.gaierror,) as e:
            pacer.note(host, False)
            return None, "resolving %s: %s" % (host, e)
        except (ConnectionResetError, socket.timeout, TimeoutError) as e:
            last_err = "%s: %s" % (host, e or type(e).__name__)
            pacer.note(host, False)
            time.sleep(2.0 * (attempt + 1))  # back off; a reset means "slow down"
        except OSError as e:
            pacer.note(host, False)
            return None, "%s: %s" % (host, e)
    return None, last_err or "no answer"


# --------------------------------------------------------------------------
# minimal DNS: does this name have NS records?
# --------------------------------------------------------------------------


def _dns_encode(name: str) -> bytes:
    out = b""
    for label in name.rstrip(".").split("."):
        raw = label.encode("idna") if any(ord(c) > 127 for c in label) else label.encode()
        out += bytes([len(raw)]) + raw
    return out + b"\0"


def dns_has_ns(name: str, timeout: float = 4.0) -> bool | None:
    """True/False if a resolver answered, None if none of them did.

    NS records at the name itself are proof of a delegation, which for a
    second-level name means somebody registered it. The converse is not true
    (a registered name need not be delegated), which is exactly why this is
    used only to *find* a name that is certainly taken.
    """
    query = struct.pack(">HHHHHH", random.randrange(65536), 0x0100, 1, 0, 0, 0)
    query += _dns_encode(name) + struct.pack(">HH", 2, 1)  # NS, IN
    for server in RESOLVERS:
        try:
            sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            sock.settimeout(timeout)
            try:
                sock.sendto(query, (server, 53))
                data, _ = sock.recvfrom(4096)
            finally:
                sock.close()
        except OSError:
            continue
        if len(data) < 12:
            continue
        _, flags, _, ancount, _, _ = struct.unpack(">HHHHHH", data[:12])
        rcode = flags & 0xF
        if rcode == 3:  # NXDOMAIN
            return False
        if rcode != 0:
            continue
        return ancount > 0
    return None


