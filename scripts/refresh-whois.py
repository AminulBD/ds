def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "stage",
        choices=["discover", "probe", "merge", "verify", "all", "report"],
        nargs="?",
        default="all",
    )
    ap.add_argument("--jobs", type=int, default=12, help="hosts probed in parallel")
    ap.add_argument(
        "--host-gap",
        type=float,
        default=1.5,
        help="minimum seconds between two queries to the same WHOIS host",
    )
    ap.add_argument(
        "--iana-gap", type=float, default=0.5, help="seconds between whois.iana.org queries"
    )
    ap.add_argument("--only", help="comma separated TLDs, for testing a few")
    ap.add_argument("--reprobe", action="store_true", help="ignore the probe cache")
    ap.add_argument(
        "--retry-failed",
        action="store_true",
        help="re-probe only the TLDs whose cached probe failed to get an answer",
    )
    ap.add_argument(
        "--refresh-known", action="store_true", help="re-ask IANA about every TLD"
    )
    ap.add_argument("--dry-run", action="store_true", help="do not write whois.json")
    ap.add_argument(
        "--binary",
        default="target/release/ds",
        help="the ds binary the verify stage drives (default target/release/ds)",
    )
    ap.add_argument(
        "--sample",
        type=int,
        default=0,
        help="verify only this many TLDs, chosen at random (default: all of them)",
    )
    ap.add_argument(
        "--verify-jobs", type=int, default=6, help="ds --concurrency during verify"
    )
    ap.add_argument(
        "--no-retry", action="store_true", help="verify: skip the gentle second pass"
    )
    ap.add_argument(
        "--show-unknown",
        action="store_true",
        help="verify: list the lookups that stayed UNKNOWN, with the reason",
    )
    args = ap.parse_args()
    args.only = (
        {t.strip().strip(".").lower() for t in args.only.split(",") if t.strip()}
        if args.only
        else None
    )

    CACHE.mkdir(parents=True, exist_ok=True)

    def on_sigint(*_):
        log("\ninterrupted — finishing in-flight queries and saving the cache")
        STOP.set()

    import signal

    signal.signal(signal.SIGINT, on_sigint)

    servers = read_json(CACHE / "servers.json", {}) or {}
    probes = read_json(CACHE / "probes.json", {}) or {}

    if args.stage in ("discover", "all"):
        servers = stage_discover(args)
    if args.stage in ("probe", "all"):
        probes = stage_probe(args, servers)
    if args.stage == "report":
        stage_merge(argparse.Namespace(**{**vars(args), "dry_run": True}), probes, servers)
    if args.stage in ("merge", "all"):
        stage_merge(args, probes, servers)
    if args.stage == "verify":
        return stage_verify(args, probes)
    return 0


if __name__ == "__main__":
    sys.exit(main())
