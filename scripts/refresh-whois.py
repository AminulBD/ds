#!/usr/bin/env python3
"""Harvest WHOIS servers from IANA, verify them, and refresh `whois.json`.

Nothing here trusts IANA's word for it. A server only reaches `whois.json`
after this script has, for that exact TLD:

  1. resolved the host and got an answer out of it on port 43;
  2. asked it about a 16-character random label nobody can have registered,
     and had the answer read as AVAILABLE;
  3. asked it about a name proven registered *independently of WHOIS* — the
     name has NS records in the DNS — and had the answer read as TAKEN;
  4. found a needle for the "free" answer from a hand-vetted list of real
     registry phrasings, and confirmed that needle is absent (unnegated) from
     the "taken" answer.

Step 4 is allowed to come up empty: `available` is then left as `""`, which
makes `ds` fall back to the same generic markers it already uses for a server
discovered through an IANA referral at runtime. What never happens is a
*guessed* needle — a wrong needle reports a registered domain as AVAILABLE,
and that is the one mistake this project refuses to make.

The verdicts are produced by `whois_classify.py`, a line-for-line port of
`classify()` in `src/whois.rs`, so "reads as AVAILABLE" means what `ds` itself
would decide when handed that response.

Stages (all cached under scripts/.whois-cache/, so a re-run is cheap):

    ./scripts/refresh-whois.py discover   # IANA TLD list + whois: host per TLD
    ./scripts/refresh-whois.py probe      # DNS + the two WHOIS probes per TLD
    ./scripts/refresh-whois.py merge      # verdicts -> whois.json + report
    ./scripts/refresh-whois.py all        # all three

    cargo build --release
    ./scripts/refresh-whois.py verify     # re-check the table through ds itself

Being a good citizen is the point of the pacing knobs. Queries to one registry
are serialised with a gap between them (--host-gap, default 1.5s), and the key
is the *address* the server resolves to rather than its name — hundreds of
`whois.nic.<tld>` aliases sit on a handful of shared back ends, and pacing by
name would let this script hammer one machine from twenty directions at once.
At most --jobs hosts are in flight, and a back end that fails repeatedly is
rested rather than retried into the ground. A slower polite run is the correct
trade; expect the whole thing to take hours.
"""

